// Generates EVIDENCE.md and evidence.json: what each example asserts and what happened
// when it was run. Run with `npm run evidence`. The manuscript does not read these
// files; they are the experimental record behind its claims.
//
// Levels, as in review pass 3:
//   1  does it typecheck against the pinned declarations
//   2  does it execute
//   3  does the observed behaviour support the claim the chapter makes
// Levels 1 and 2 are measured here. Level 3 is the asserted claim (the test name)
// plus the fact that its assertions held; whether the claim is the right one is a
// reading task for a person.
import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const chaptersDir = join(here, "..", "content", "books", "pi");
const pkg = (name) => JSON.parse(readFileSync(join(here, "node_modules", "@earendil-works", name, "package.json"), "utf8")).version;
const versions = { "pi-ai": pkg("pi-ai"), "pi-agent-core": pkg("pi-agent-core"), "pi-coding-agent": pkg("pi-coding-agent"), node: process.version };

// Level 1: one typecheck for everything, then per-file attribution of errors.
const tsc = spawnSync("npx", ["tsc", "-p", ".", "--pretty", "false"], { cwd: here, encoding: "utf8", shell: true });
const tscErrors = (tsc.stdout + tsc.stderr).split("\n").filter((l) => /\(\d+,\d+\): error/.test(l));
const compiles = (file) => !tscErrors.some((l) => l.replace(/\\/g, "/").startsWith(file.replace(/\\/g, "/") + "("));

// Test files, and the chapter each belongs to (from the directory name chNN-...).
const walk = (d) =>
	readdirSync(d).flatMap((n) => {
		if (n === "node_modules") return [];
		const p = join(d, n);
		return statSync(p).isDirectory() ? walk(p) : [p];
	});
const testFiles = walk(here).filter((f) => f.endsWith(".test.ts")).map((f) => relative(here, f).replace(/\\/g, "/")).sort();
const chapterOf = (f) => (f.match(/^ch(\d+)-/) ?? [])[1] ?? null;

// evidence_scope: how far from the shipped product the evidence is.
//   declarations         compared with the exported types at compile time
//   in_process_runtime   Pi's packages, run in this process (real extension runtime, scripted model)
//   shipped_binary       the `pi` executable, run as a child process
//   real_model           a live provider (none yet)
function scopeOf(file) {
	const src = readFileSync(join(here, file), "utf8");
	if (src.includes("harness/cli.ts")) return "shipped_binary";
	return "in_process_runtime";
}

const rows = [];
for (const file of testFiles) {
	const r = spawnSync(process.execPath, ["--test", file], { cwd: here, encoding: "utf8" });
	const out = r.stdout;
	for (const m of out.matchAll(/^(✔|✖) (.+?) \(([\d.]+)ms\)$/gm)) {
		rows.push({
			chapter: chapterOf(file),
			file,
			claim_class: "OBSERVED",
			evidence_scope: scopeOf(file),
			compile: compiles(file) ? "pass" : "FAIL",
			runtime: m[1] === "✔" ? "pass" : "FAIL",
			claim: m[2],
			ms: Math.round(Number(m[3])),
		});
	}
}

// Declaration checks: assert-equal.ts files compile only if the book's declarations match Pi's exports.
for (const f of walk(here).filter((x) => x.endsWith("assert-equal.ts")).map((x) => relative(here, x).split("\\").join("/")).sort()) {
	rows.push({
		chapter: chapterOf(f),
		file: f,
		claim_class: "DOCUMENTED",
		evidence_scope: "declarations",
		compile: compiles(f) ? "pass" : "FAIL",
		runtime: compiles(f) ? "pass" : "FAIL",
		claim: "the declarations printed in the chapter are mutually assignable with, and have the same keys as, the exported types",
		ms: 0,
	});
}

// Embedded blocks: which chapter shows which file, and how.
const embeds = [];
for (const f of readdirSync(chaptersDir).filter((x) => x.endsWith(".md"))) {
	const text = readFileSync(join(chaptersDir, f), "utf8").replace(/\r\n/g, "\n");
	const num = f.match(/^(\d+)/);
	if (!num) continue;
	const chapter = String(Number(num[1]));
	for (const m of text.matchAll(/<!-- (example|excerpt|declaration|documented-not-run|illustrative)(?:: (\S+))? -->\n```/g)) {
		embeds.push({ chapter, kind: m[1], source: m[2] ?? "" });
	}
}

const failing = rows.filter((r) => r.runtime !== "pass" || r.compile !== "pass");
const byChapter = new Map();
for (const r of rows) byChapter.set(r.chapter ?? "-", [...(byChapter.get(r.chapter ?? "-") ?? []), r]);

const lines = [];
lines.push("# Evidence ledger", "");
lines.push("Generated by `npm run evidence`. Do not edit.", "");
lines.push(`Pi release: pi-ai ${versions["pi-ai"]}, pi-agent-core ${versions["pi-agent-core"]}, pi-coding-agent ${versions["pi-coding-agent"]}. Node ${versions.node}.`, "");
lines.push(`Typecheck (level 1): ${tscErrors.length === 0 ? "clean" : tscErrors.length + " error(s)"}. Ledger rows (one per test or declaration check, so not the same as the test count npm test prints): ${rows.length - failing.length} of ${rows.length} hold.`, "");
const scopes = rows.reduce((a, r) => ((a[r.evidence_scope] = (a[r.evidence_scope] ?? 0) + 1), a), {});
lines.push("By evidence scope: " + Object.entries(scopes).map(([k, v]) => `${k} ${v}`).join(", ") + ". There is no `real_model` evidence yet.", "");
lines.push("Claim classes: OBSERVED means a test ran and its assertions held; DOCUMENTED means the claim is a statement of Pi's declarations, checked at compile time; PROPOSED claims are this book's own and have no row here unless a test backs them.", "");
lines.push("The model is always the faux provider. Every row therefore shows that the code around a model behaves as claimed, and none shows how a real model behaves.", "");
for (const [ch, rs] of [...byChapter.entries()].sort((a, b) => Number(a[0]) - Number(b[0]))) {
	lines.push(`## Chapter ${ch}`, "");
	lines.push("| File | Class | Scope | Compile | Runtime | Asserted claim |", "|---|---|---|---|---|---|");
	for (const r of rs) lines.push("| `" + r.file + "` | " + r.claim_class + " | " + r.evidence_scope + " | " + r.compile + " | " + r.runtime + " | " + r.claim.split("|").join("/") + " |");
	lines.push("");
}
lines.push("## Code shown in the manuscript", "");
lines.push("| Chapter | Kind | Source |", "|---|---|---|");
for (const e of embeds.sort((a, b) => Number(a.chapter) - Number(b.chapter))) lines.push(`| ${e.chapter} | ${e.kind} | ${e.source ? "`" + e.source + "`" : ""} |`);
lines.push("");
const counts = embeds.reduce((a, e) => ((a[e.kind] = (a[e.kind] ?? 0) + 1), a), {});
lines.push("Counts: " + Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ") + ".", "");

writeFileSync(join(here, "EVIDENCE.md"), lines.join("\n"));
writeFileSync(join(here, "evidence.json"), JSON.stringify({ versions, typecheckErrors: tscErrors.length, rows, embeds }, null, 2));
console.log(`evidence: ${rows.length} claims, ${failing.length} failing, ${embeds.length} embedded blocks, typecheck ${tscErrors.length ? "FAILED" : "clean"}`);
if (failing.length || tscErrors.length) process.exit(1);
